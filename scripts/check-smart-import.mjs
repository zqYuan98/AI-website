import assert from "node:assert/strict";
import { createTsLoader } from "./lib/load-ts.mjs";
const load = createTsLoader();
const { canonicalBookmarkUrl, parseBookmarkHtmlDetailed } = load("src/lib/bookmark-import.ts");
const { parseImportSources, regroupImportSources, editImportSource, importSummary, filteredImportGroups, projectImportAcceptance, importResult, importRelationshipHash, importGroupDto } = load("src/lib/smart-import-domain.ts");
assert.equal(canonicalBookmarkUrl("https://example.com/?q=a%20b&utm_source=x"), canonicalBookmarkUrl("https://example.com/?q=a%20b"));
assert.equal(canonicalBookmarkUrl("https://example.com/?%75tm_source=x&a=%2f&b=2"), "https://example.com/?a=%2f&b=2");
for (const [a,b] of [["/a", "/b"], ["/a", "/a/"], ["/?a=1&b=2", "/?b=2&a=1"], ["/#a", "/#b"]]) assert.notEqual(canonicalBookmarkUrl(`https://example.com${a}`), canonicalBookmarkUrl(`https://example.com${b}`));
const parsed = parseBookmarkHtmlDetailed('<DL><H3>First</H3><DL><A HREF="https://example.com/a">A</A></DL><H3>Second</H3><DL><A HREF="https://example.com/a?utm_source=x">Again</A><A HREF="javascript:alert(1)">Bad</A></DL></DL>');
assert.equal(parsed.length, 3);
assert.equal(parsed[0].sourceFolder, "First");
assert.equal(parsed[1].sourceFolder, "Second");
assert(parsed[2].invalidReason);
const emptyPublication = { version: 1, publishedAt: "", resources: [] };
const origins = parseImportSources('<DL><H3>One</H3><DL><A HREF="https://example.com/a">First</A></DL><H3>Two</H3><DL><A HREF="https://example.com/a?utm_source=x">Second</A></DL></DL>', "html");
let groups = regroupImportSources(origins, [], [], emptyPublication);
assert.equal(groups.length, 1);
assert.equal(groups[0].sourceCount, 2);
const stable = groups[0].id;
groups[0].manualFields = { category: "开发与技术" }; groups[0].categoryConfirmed = true; groups[0].decision = "keep";
for (const source of origins) source.intent = { decision: "keep", fields: { category: "开发与技术" }, categoryConfirmed: true };
origins[1] = editImportSource(origins[1], { url: "https://example.com/b" });
groups = regroupImportSources(origins, groups, [], emptyPublication);
assert.equal(groups.length, 2);
assert(groups.every(group => group.decision === "keep" && group.categoryConfirmed));
assert.equal(groups[0].id, stable);
origins[0] = editImportSource(origins[0], { excluded: true });
groups = regroupImportSources(origins, groups, [], emptyPublication);
assert.equal(groups.length, 1);
assert.equal(importSummary(origins, groups).excludedSources, 1);
origins[0] = editImportSource(origins[0], { excluded: false });
groups = regroupImportSources(origins, groups, [], emptyPublication);
assert.equal(groups.length, 2);
assert.equal(filteredImportGroups(groups, { folder: "Two" }).length, 1);
assert.throws(() => parseImportSources("x".repeat(2 * 1024 * 1024 + 1), "html"));
assert.throws(() => parseImportSources(Array(5001).fill("https://example.com").join("\n"), "lines"));
const peers = regroupImportSources(parseImportSources("http://github.com/docs\nhttps://github.com/docs", "lines"), [], [], emptyPublication);
assert.equal(peers.length, 2);
assert(peers.every(group => group.suspectedGroupCount === 1 && group.suspectedGroups[0].id !== group.id));
assert.equal(filteredImportGroups(peers, { view: "review" }).length, 2);
assert.equal(filteredImportGroups(peers, { view: "suggested" }).length, 0);
const classified = regroupImportSources(parseImportSources("https://custom.example.com/article", "lines"), [], [{ id: "known", name: "Known", url: "https://custom.example.com/", status: "organized", visibility: "private", category: "学习与研究" }], emptyPublication);
assert.equal(classified[0].suggestion.category, "学习与研究");
assert.equal(classified[0].suggestion.reason, "参考资源库同站点已确认分类");

const manual = structuredClone(classified[0]);
manual.manualFields = { name: "Owner title", kind: "article", category: "写作与知识", description: "", tags: [] };
manual.fields = { ...manual.fields, ...manual.manualFields }; manual.categoryConfirmed = true;
manual.suggestion = { kind: "tool", category: "AI 与自动化", description: "Model description", tags: ["model"], reason: "Fixture", source: "model", confidence: "clear" };
const beforeProjection = structuredClone(manual), projected = projectImportAcceptance(manual);
assert.deepEqual(projected.fields, manual.fields, "Explicit empty strings and empty tag arrays must beat a model suggestion.");
assert.deepEqual(projected.adoptedFields, []);
assert.deepEqual(manual, beforeProjection, "Projection must not mutate staged owner data.");
assert.equal(importGroupDto(manual).proposal.fields.description, "");
assert(!Object.hasOwn(importGroupDto(manual), "manualFields"));
assert.deepEqual(projectImportAcceptance(classified[0], "preserve").fields, classified[0].fields);
assert.equal(projectImportAcceptance(classified[0]).fields.category, "学习与研究");
const historical = structuredClone(classified[0]);
historical.readOnly = true; historical.outcome = { kind: "created", resourceId: "old-preserve-import", completedAt: "" };
assert.equal(importGroupDto(historical).proposal.status, "inbox");
assert.equal(importGroupDto(historical).proposal.fields.category, historical.fields.category);
assert.equal(importGroupDto(historical).proposal.fields.description, historical.fields.description);
assert.deepEqual(importGroupDto(historical).proposal.adoptedFields, [], "Viewing an old completed import cannot accept suggestions that were never saved.");

const resultOrigins = parseImportSources("https://github.com/result-ready\nhttps://github.com/result-ready?utm_source=copy\nhttps://unknown.example.com/a\nhttps://existing.example.com/a\nhttps://archive.example.com/a\nhttps://publication.example.com/a\njavascript:bad\nhttps://excluded.example.com/a", "lines");
resultOrigins.at(-1).excluded = true;
const resultGroups = regroupImportSources(resultOrigins, [], [
  { id: "existing", name: "Existing", url: "https://existing.example.com/a", status: "organized", visibility: "private", category: "学习与研究" },
  { id: "archive", name: "Archive", url: "https://archive.example.com/a", status: "archived", visibility: "private", category: "学习与研究" },
], { ...emptyPublication, resources: [{ id: "publication", name: "Published", url: "https://publication.example.com/a", visibility: "public" }] });
const resultSummary = importSummary(resultOrigins, resultGroups);
assert.deepEqual(resultSummary.resultCounts, { ready: 1, review: 3, skipped: 1, collected: 0 });
assert.equal(Object.values(resultSummary.resultCounts).reduce((a, b) => a + b, 0), resultSummary.groupTotal);
assert.equal(resultSummary.skippedSources, 3, "Existing, invalid and excluded origins are source units; duplicate origins of a ready group are not skipped.");
assert.equal(resultSummary.duplicateSources, 1);
for (const state of ["ready", "review", "skipped", "collected"]) assert.equal(filteredImportGroups(resultGroups, { resultStatus: state }).length, resultSummary.resultCounts[state]);
const unknown = resultGroups.find(group => group.representative.url.includes("unknown"));
unknown.manualFields.category = "设计与创作"; unknown.fields.category = "设计与创作"; unknown.categoryConfirmed = true;
assert.equal(importResult(unknown).status, "ready", "A confirmed category resolves unclear classification.");
const peer = peers[0];
peer.manualFields.category = "开发与技术"; peer.categoryConfirmed = true;
assert.equal(importResult(peer).status, "review", "Setting a category cannot acknowledge a suspected duplicate.");
peer.decision = "keep"; peer.reviewAcknowledgement = importRelationshipHash(peer);
assert.equal(importResult(peer).status, "ready");
peer.suspectedScopeHash = "changed-relationship";
assert.equal(importResult(peer).status, "review", "A changed relationship invalidates the earlier explicit acknowledgement.");
const archived = resultGroups.find(group => group.matchKind === "archived");
archived.decision = "keep"; archived.reviewAcknowledgement = importRelationshipHash(archived);
assert.equal(importResult(archived).status, "review", "Restoring an archive always requires its separate resolution flow.");
const ready = resultGroups.find(group => group.sourceCount === 2);
ready.error = "Capacity fixture"; assert.equal(importResult(ready).status, "review"); ready.error = null;
ready.readOnly = true; ready.outcome = { kind: "created", resourceId: "created", completedAt: "" };
assert.equal(importResult(ready).status, "collected");
assert(!filteredImportGroups(resultGroups, { resultStatus: "skipped" }).some(group => group.id === ready.id));
console.log("PASS: conservative URL identity, retained origins, manual-first read-only proposals, mutually exclusive result counts and relationship review guards.");
